-- =========================================================
-- 1. STRIPE PAYMENT ATTEMPTS
-- One booking may have multiple payment attempts.
-- Historical attempts must be preserved.
-- =========================================================

CREATE TABLE IF NOT EXISTS stripe_payment_attempts (
    id BIGSERIAL PRIMARY KEY,

    booking_id INTEGER NOT NULL
        REFERENCES bookings(id) ON DELETE RESTRICT,

    stripe_checkout_session_id TEXT UNIQUE,

    stripe_payment_intent_id TEXT UNIQUE,

    -- Generated by our backend for Stripe API idempotency.
    idempotency_key TEXT NOT NULL UNIQUE,

    -- Stripe uses the smallest currency unit (EUR cents).
    amount_cents BIGINT NOT NULL
        CHECK (amount_cents > 0),

    currency VARCHAR(3) NOT NULL DEFAULT 'eur'
        CHECK (currency = 'eur'),

    status VARCHAR(30) NOT NULL DEFAULT 'created'
        CHECK (
            status IN (
                'created',
                'completed',
                'failed',
                'expired',
                'refund_pending',
                'refunded',
                'refund_failed'
            )
        ),

    session_expires_at TIMESTAMPTZ,

    failure_message TEXT,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);


-- =========================================================
-- 2. STRIPE WEBHOOK EVENTS
-- Store event IDs to prevent duplicate processing.
-- Do not store complete Stripe payloads unnecessarily.
-- =========================================================

CREATE TABLE IF NOT EXISTS stripe_webhook_events (
    stripe_event_id TEXT PRIMARY KEY,

    event_type VARCHAR(150) NOT NULL,

    stripe_object_id TEXT,

    booking_id INTEGER
        REFERENCES bookings(id) ON DELETE RESTRICT,

    payment_attempt_id BIGINT
        REFERENCES stripe_payment_attempts(id) ON DELETE RESTRICT,

    processing_status VARCHAR(20) NOT NULL DEFAULT 'received'
        CHECK (
            processing_status IN (
                'received',
                'processing',
                'processed',
                'failed'
            )
        ),

    attempt_count INTEGER NOT NULL DEFAULT 0
        CHECK (attempt_count >= 0),

    last_error TEXT,

    received_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    processed_at TIMESTAMPTZ,

    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);


-- =========================================================
-- 3. STRIPE REFUND JOBS
-- Durable refund queue for payments that must be refunded.
-- Supports retries without accidentally issuing duplicate
-- refunds.
-- =========================================================

CREATE TABLE IF NOT EXISTS stripe_refund_jobs (
    id BIGSERIAL PRIMARY KEY,

    booking_id INTEGER NOT NULL
        REFERENCES bookings(id) ON DELETE RESTRICT,

    payment_attempt_id BIGINT NOT NULL UNIQUE
        REFERENCES stripe_payment_attempts(id) ON DELETE RESTRICT,

    stripe_payment_intent_id TEXT NOT NULL,

    amount_cents BIGINT NOT NULL
        CHECK (amount_cents > 0),

    currency VARCHAR(3) NOT NULL DEFAULT 'eur'
        CHECK (currency = 'eur'),

    reason TEXT NOT NULL,

    status VARCHAR(20) NOT NULL DEFAULT 'pending'
        CHECK (
            status IN (
                'pending',
                'processing',
                'succeeded',
                'needs_attention'
            )
        ),

    -- Stable key: reused for every retry of the same refund.
    idempotency_key TEXT NOT NULL UNIQUE,

    stripe_refund_id TEXT UNIQUE,

    attempt_count INTEGER NOT NULL DEFAULT 0
        CHECK (attempt_count >= 0),

    next_attempt_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    last_error TEXT,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    completed_at TIMESTAMPTZ
);


-- =========================================================
-- 4. INDEXES
-- Improve booking lookup, webhook processing and refund jobs.
-- =========================================================

CREATE INDEX IF NOT EXISTS idx_stripe_payment_attempts_booking
    ON stripe_payment_attempts(booking_id, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_stripe_payment_attempts_status
    ON stripe_payment_attempts(status);

CREATE INDEX IF NOT EXISTS idx_stripe_webhook_events_status
    ON stripe_webhook_events(processing_status, received_at);

CREATE INDEX IF NOT EXISTS idx_stripe_webhook_events_booking
    ON stripe_webhook_events(booking_id);

CREATE INDEX IF NOT EXISTS idx_stripe_refund_jobs_pending
    ON stripe_refund_jobs(next_attempt_at, created_at)
    WHERE status = 'pending';

CREATE INDEX IF NOT EXISTS idx_stripe_refund_jobs_booking
    ON stripe_refund_jobs(booking_id);


-- =========================================================
-- 5. DOCUMENTATION
-- =========================================================

COMMENT ON TABLE stripe_payment_attempts IS
    'Records each Stripe Checkout payment attempt for a booking.';

COMMENT ON TABLE stripe_webhook_events IS
    'Records Stripe webhook event IDs and processing results for idempotency.';

COMMENT ON TABLE stripe_refund_jobs IS
    'Durable queue of Stripe refunds requiring processing or retry.';

COMMENT ON COLUMN bookings.stripe_payment_id IS
    'Stores the Stripe PaymentIntent ID for a successfully paid booking.';


COMMIT;
